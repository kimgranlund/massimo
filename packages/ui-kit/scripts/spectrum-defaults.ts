// Generates tokens/colors/spectrum/defaults.json: the default Spectrum (both schemes, steps
// 1–12, step 1 = the endpoint tone, resolved roles) that the kit's color tokens are built from, so builds never run the
// engine. Run: npm run spectrum:defaults (test/spectrum.test.ts fails when it is stale).
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { generateSpectrum, resolveRoles, ramps, DEFAULT_ROLES } from '../tokens/colors/spectrum/index.ts';

export function spectrumDefaults() {
  const data = generateSpectrum();
  const roles = resolveRoles(data, DEFAULT_ROLES);
  return {
    $comment: 'Generated by scripts/spectrum-defaults.ts from the default Spectrum settings. Do not edit.',
    roles,
    onSolid: { light: data.schemes.light[roles.primary][8].apca.css, dark: data.schemes.dark[roles.primary][8].apca.css },
    light: ramps(data, 'light'),
    dark: ramps(data, 'dark'),
  };
}

export const DEFAULTS_PATH = fileURLToPath(new URL('../tokens/colors/spectrum/defaults.json', import.meta.url));
export const spectrumDefaultsText = () => JSON.stringify(spectrumDefaults(), null, 2) + '\n';

if (import.meta.main) {
  writeFileSync(DEFAULTS_PATH, spectrumDefaultsText());
  console.log(`wrote ${DEFAULTS_PATH}`);
}
