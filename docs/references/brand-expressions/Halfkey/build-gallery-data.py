"""Package slide manifests in index order for direct, offline browsing."""
import json
import re
from pathlib import Path

folder = Path(__file__).resolve().parent
manifests = folder / "manifests"
index = (manifests / "README.md").read_text()
names = re.findall(r"^\| \[[^\]]+\]\(([^)]+\.json)\)", index, re.MULTILINE)
if len(names) != len(set(names)) or set(names) != {p.name for p in manifests.glob("*.json")}:
    raise ValueError("List every manifest exactly once in the slide index.")
slides = [json.loads((manifests / name).read_text()) for name in names]
(folder / "gallery-data.js").write_text(
    "// Generated by build-gallery-data.py from manifests/.\n"
    + "const halfkeySlides = " + json.dumps(slides, ensure_ascii=False, indent=2) + ";\n"
)
